#!/usr/bin/env python3
"""Turn CPython's expression ASTs into typed public TileLang regression cases."""
import argparse
import ast
import json
from pathlib import Path


OUTPUT = Path(__file__).resolve().parents[1] / "tests/lean/TileLangPrecedence.lean"
OPERATORS = {
    "**": (ast.Pow, "pow"), "*": (ast.Mult, "mul"), "/": (ast.Div, "div"),
    "//": (ast.FloorDiv, "floorDiv"), "%": (ast.Mod, "mod"), "+": (ast.Add, "add"),
    "-": (ast.Sub, "sub"), "^": (ast.BitXor, "xor"), "<": (ast.Lt, "lt"),
    ">": (ast.Gt, "gt"), "<=": (ast.LtE, "le"), ">=": (ast.GtE, "ge"),
    "==": (ast.Eq, "eq"), "!=": (ast.NotEq, "ne"),
}
NODE_NAMES = dict(OPERATORS.values())


def expected(node):
    if isinstance(node, ast.Name):
        return f"(.ident `{node.id})"
    if isinstance(node, ast.Compare):
        if len(node.ops) != 1:
            return None  # The TileLang subset rejects Python comparison chains.
        return f"(.binary .{NODE_NAMES[type(node.ops[0])]} {expected(node.left)} {expected(node.comparators[0])})"
    if isinstance(node, ast.BinOp):
        return f"(.binary .{NODE_NAMES[type(node.op)]} {expected(node.left)} {expected(node.right)})"
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        return f"(.neg {expected(node.operand)})"
    if isinstance(node, ast.IfExp):
        return f"(.conditional {expected(node.body)} {expected(node.test)} {expected(node.orelse)})"
    raise ValueError(ast.dump(node))


def cases():
    for left in OPERATORS:
        for right in OPERATORS:
            yield f"a {left} b {right} c"
    for op in OPERATORS:
        yield f"-a {op} b"
        yield f"a {op} -b"
        yield f"a {op} b if c else d"
        yield f"a if b {op} c else d"
        yield f"a if b else c {op} d"
        yield f"(a {op} b) {op} c"
        yield f"a {op} (b {op} c)"
    yield "a if b else c if d else e"


def render():
    rows = []
    for expr in cases():
        value = expected(ast.parse(expr, mode="eval").body)
        rows.append(f"  ({json.dumps(expr)}, " + (f"some {value})" if value else "none)"))
    return '''-- Generated by scripts/generate_tilelang_precedence.py using Python ast.
import VeriTile.TileLang

open Lean Meta Elab Command VeriTile.TileLang

namespace VeriTile.Tests.TileLangPrecedence

-- None denotes Python's comparison chain: the public TileLang grammar must reject it.
private def cases : List (String × Option Value) := [
''' + ",\n".join(rows) + '''
]

set_option maxRecDepth 8192 in
set_option maxHeartbeats 5000000 in
run_cmd do
  let env ← getEnv
  for (source, expected) in cases do
    let unit := "tilelang { @tilelang.jit def probe(): { with T.Kernel(1) as bx: { x = " ++
      source ++ " }; return x } }"
    match Parser.runParserCategory env `term unit, expected with
    | .error _, none => pure ()
    | .error e, some _ => throwError "{source}: public parser rejected the expression: {e}"
    | .ok _, none => throwError "{source}: public parser accepted a chained comparison"
    | .ok stx, some want =>
      let p ← liftTermElabM <| Term.evalTerm Program (mkConst ``Program) stx
      let .direct fn := p.definition | throwError "{source}: expected a direct definition"
      let [.kernel _ _ [.assign _ got], .ret _] := fn.body
        | throwError "{source}: expected the assignment in the kernel"
      unless got == want do
        throwError "{source}: expected {repr want}, got {repr got}"

end VeriTile.Tests.TileLangPrecedence
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if OUTPUT.read_text() != generated:
            parser.exit(1, "stale TileLang precedence test\n")
    else:
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
